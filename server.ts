async function generateGeminiContent(options: {
  contents: string;
  systemInstruction?: string;
  responseMimeType?: string;
}): Promise<string | null> {
  if (!ai) return null;
  const models = ['gemini-2.5-flash', 'gemini-3.8-flash'];
  
  for (const model of models) {
    try {
      const timeoutPromise = new Promise<null>((resolve) => setTimeout(() => resolve(null), 2500));
      const generatePromise = ai.models.generateContent({
        model,
        contents: options.contents,
        config: {
          systemInstruction: options.systemInstruction,
          responseMimeType: options.responseMimeType,
        },
      }).then(res => (res && res.text ? res.text : null)).catch(() => null);

      const result = await Promise.race([generatePromise, timeoutPromise]);
      if (result) {
        return result;
      }
    } catch (err: unknown) {
      console.warn(`Model ${model} timed out or failed`);
    }
  }
  return null;
}

function parseJsonSafely<T>(raw: string | null | undefined, fallback: T): T {
  if (!raw) return fallback;
  try {
    const cleaned = raw
      .replace(/```(?:json)?/gi, '')
      .replace(/```/g, '')
      .trim();
    return JSON.parse(cleaned) as T;
  } catch (err) {
    console.warn('JSON safe parse fallback triggered:', err);
    return fallback;
  }
}

